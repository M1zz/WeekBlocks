//  값을 받는 선을 '기능'이 아니라 **'적기'**에 그었다. 잠긴 기기는 상대 기기의 할 일을
//  받아 보기는 하지만 적지는 못한다. 안 적으니 보낼 것이 없고, 그래서 결과적으로
//  **산 쪽 → 안 산 쪽** 한 방향이 된다.
//
//  ⚠️ 동기화 엔진에는 방향이 없다. `NSPersistentCloudKitContainer`는 받기와 보내기를
//     따로 못 끈다 — 켜면 둘 다, 끄면 둘 다다. 그래서 방향은 엔진이 아니라 **사람이
//     적을 수 있는지**로 만든다. 이 파일이 그 한 줄이다.
//
//  ⚠️ 잠근다고 **이미 적어 둔 것을 숨기지 않는다.** 보이고, 읽히고, 끝낸 것도 그대로다.
//     쓰던 사람의 목록이 비면 그건 값을 받는 게 아니라 뺏는 것이다.
//

import Foundation

enum TodoAccess {

    /// 이 기기에서 할 일을 적고 고칠 수 있는가.
    ///
    /// 화면들은 **이 값 하나만** 본다. 상품 구성이 바뀌어도 여기 한 줄만 고치면 된다.
    static var canEdit: Bool { MacEntitlement.isUnlocked }

    static let lockedTitle = "이 기기에서는 읽기만 됩니다"
    static let lockedNote = "적는 것은 열어야 합니다. 이미 적어 둔 것은 그대로 보이고, 아이폰에서 적은 것도 계속 내려옵니다."
}
